import type { SpriteDef } from '../components/world/PixelSprite'

// The Capiture icon family: 16×16, light from the top-left, three tones per
// material. Only the fills are drawn here; the 1 px ink outline is generated,
// so every icon has exactly the same stroke.

const INK = '#241a16'

function icon(rows: string[], palette: Record<string, string>): SpriteDef {
  const h = rows.length
  const w = rows[0].length
  const filled = (x: number, y: number) => x >= 0 && y >= 0 && x < w && y < h && rows[y][x] !== '.'
  const grid = rows.map((row, y) =>
    [...row]
      .map((ch, x) => {
        if (ch !== '.') return ch
        return filled(x + 1, y) || filled(x - 1, y) || filled(x, y + 1) || filled(x, y - 1) ? 'o' : '.'
      })
      .join(''),
  )
  return { grid, palette: { ...palette, o: INK } }
}

